"""
EXP028a: FULLY PARAMETERIZED 4×4 COIN FOR NON-SEPARABLE QUANTUM WALKS
Generalizing Dukes' 2×2 coin (ρ, α, β) to 4×4 with phases

Dukes' 2×2 coin:
C₂ = [[√ρ, √(1-ρ)e^{iα}], [√(1-ρ)e^{iβ}, -√ρ e^{i(α+β)}]]

For 4×4, we need a structure that maintains unitarity while allowing
independent phase control for each direction.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import expm
import warnings
warnings.filterwarnings('ignore')


class FullyParameterized4x4Coin:
    """
    Fully parameterized 4×4 coin for 2D quantum walks.

    Parameterization strategy:
    1. Base amplitudes from probabilities (p, q, r, s)
    2. Phases for each direction (φ_R, φ_L, φ_U, φ_D)
    3. Coupling phases (θ_RL, θ_RU, θ_RD, etc.) for interference

    Total parameters: 4 probabilities + 4 direction phases + 6 coupling phases = 14
    (plus global phase = 15 total for SU(4))
    """

    @staticmethod
    def dukes_2x2(rho, alpha, beta):
        """Dukes' original 2×2 SU(2) coin."""
        return np.array([
            [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * alpha)],
            [np.sqrt(1-rho) * np.exp(1j * beta), -np.sqrt(rho) * np.exp(1j * (alpha + beta))]
        ])

    @staticmethod
    def separable_with_phases(rho_x, alpha_x, beta_x, rho_y, alpha_y, beta_y):
        """
        Separable 4×4 coin with phases: C = C_x ⊗ C_y

        This uses Dukes' 2×2 coins for x and y directions independently.
        Total parameters: 6 (3 per 2×2 coin)
        """
        C_x = FullyParameterized4x4Coin.dukes_2x2(rho_x, alpha_x, beta_x)
        C_y = FullyParameterized4x4Coin.dukes_2x2(rho_y, alpha_y, beta_y)
        return np.kron(C_x, C_y)

    @staticmethod
    def grover_like_bias(p, q, r, s, phi_R=0, phi_L=0, phi_U=0, phi_D=0):
        """
        Grover-like biased coin with direction phases.

        Parameters:
        - p, q, r, s: probabilities for R, L, U, D (must sum to 1)
        - phi_R, phi_L, phi_U, phi_D: phase offsets for each direction

        The base matrix has the Grover structure, then each row gets a phase.
        """
        sqrt_p, sqrt_q, sqrt_r, sqrt_s = np.sqrt(p), np.sqrt(q), np.sqrt(r), np.sqrt(s)

        # Base Grover-like matrix (real)
        C_base = np.array([
            [sqrt_p, sqrt_q, sqrt_r, sqrt_s],
            [sqrt_p, -sqrt_q, sqrt_r, -sqrt_s],
            [sqrt_p, sqrt_q, -sqrt_r, -sqrt_s],
            [sqrt_p, -sqrt_q, -sqrt_r, sqrt_s]
        ])

        # Apply row phases (each row corresponds to output direction)
        row_phases = np.array([np.exp(1j * phi_R), np.exp(1j * phi_L),
                                np.exp(1j * phi_U), np.exp(1j * phi_D)])

        C = C_base * row_phases[:, np.newaxis]

        # Also add column phases (input direction phases)
        col_phases = np.array([np.exp(1j * phi_R), np.exp(1j * phi_L),
                                np.exp(1j * phi_U), np.exp(1j * phi_D)])
        C = C * col_phases[np.newaxis, :]

        return C

    @staticmethod
    def full_parameterized(p, q, r, s,
                           alpha_R, alpha_L, alpha_U, alpha_D,
                           beta_RL, beta_RU, beta_RD, beta_LU, beta_LD, beta_UD):
        """
        Fully parameterized 4×4 coin with 14 parameters.

        Parameters:
        - p, q, r, s: probabilities (4 parameters, sum to 1)
        - alpha_*: direction phases (4 parameters)
        - beta_**: coupling phases (6 parameters)

        Structure: C = D_out * G * D_in, where:
        - D_out = diag(e^{iα_R}, e^{iα_L}, e^{iα_U}, e^{iα_D})
        - G = Grover-like matrix with coupling phases
        - D_in = diag(e^{iα_R}, e^{iα_L}, e^{iα_U}, e^{iα_D}) * coupling phases
        """
        sqrt_p, sqrt_q, sqrt_r, sqrt_s = np.sqrt(p), np.sqrt(q), np.sqrt(r), np.sqrt(s)

        # Base amplitude matrix
        A = np.array([
            [sqrt_p, sqrt_q, sqrt_r, sqrt_s],
            [sqrt_p, -sqrt_q, sqrt_r, -sqrt_s],
            [sqrt_p, sqrt_q, -sqrt_r, -sqrt_s],
            [sqrt_p, -sqrt_q, -sqrt_r, sqrt_s]
        ])

        # Apply coupling phases (off-diagonal phases)
        A[0, 1] *= np.exp(1j * beta_RL)
        A[0, 2] *= np.exp(1j * beta_RU)
        A[0, 3] *= np.exp(1j * beta_RD)
        A[1, 2] *= np.exp(1j * beta_LU)
        A[1, 3] *= np.exp(1j * beta_LD)
        A[2, 3] *= np.exp(1j * beta_UD)
        A[1, 0] *= np.exp(1j * beta_RL)
        A[2, 0] *= np.exp(1j * beta_RU)
        A[3, 0] *= np.exp(1j * beta_RD)
        A[2, 1] *= np.exp(1j * beta_LU)
        A[3, 1] *= np.exp(1j * beta_LD)
        A[3, 2] *= np.exp(1j * beta_UD)

        # Apply output direction phases
        out_phases = np.array([np.exp(1j * alpha_R), np.exp(1j * alpha_L),
                                np.exp(1j * alpha_U), np.exp(1j * alpha_D)])
        A = A * out_phases[:, np.newaxis]

        # Apply input direction phases
        in_phases = np.array([np.exp(1j * alpha_R), np.exp(1j * alpha_L),
                               np.exp(1j * alpha_U), np.exp(1j * alpha_D)])
        A = A * in_phases[np.newaxis, :]

        # Normalize to ensure unitarity (Gram-Schmidt)
        # This ensures columns are orthonormal
        C = A.copy()
        for i in range(4):
            # Normalize column i
            norm = np.sqrt(np.sum(np.abs(C[:, i])**2))
            if norm > 0:
                C[:, i] /= norm
            # Orthogonalize against previous columns
            for j in range(i):
                C[:, i] -= np.vdot(C[:, j], C[:, i]) * C[:, j]

        return C

    @staticmethod
    def random_su4():
        """Generate a random SU(4) matrix."""
        H = np.random.randn(4, 4) + 1j * np.random.randn(4, 4)
        H = H + H.conj().T
        H = H - np.trace(H) / 4 * np.eye(4)
        return expm(1j * H)


class NonSeparableWalkPhased:
    """Non-separable quantum walk on torus with fully parameterized coin."""

    def __init__(self, n, m):
        self.n = n
        self.m = m
        self.N = n * m
        self.dim = 4 * self.N
        self.R, self.L, self.U, self.D = 0, 1, 2, 3
        self._build_neighbors()

    def _build_neighbors(self):
        self.right_neighbor = np.zeros(self.N, dtype=int)
        self.left_neighbor = np.zeros(self.N, dtype=int)
        self.up_neighbor = np.zeros(self.N, dtype=int)
        self.down_neighbor = np.zeros(self.N, dtype=int)

        for i in range(self.n):
            for j in range(self.m):
                idx = i * self.m + j
                self.right_neighbor[idx] = i * self.m + ((j + 1) % self.m)
                self.left_neighbor[idx] = i * self.m + ((j - 1) % self.m)
                self.up_neighbor[idx] = ((i - 1) % self.n) * self.m + j
                self.down_neighbor[idx] = ((i + 1) % self.n) * self.m + j

    def build_evolution_operator(self, coin):
        """Build U = S · (I_N ⊗ C)."""
        S_total = np.zeros((self.dim, self.dim), dtype=complex)

        for pos in range(self.N):
            S_total[4 * self.right_neighbor[pos] + self.R, 4 * pos + self.R] = 1
            S_total[4 * self.left_neighbor[pos] + self.L, 4 * pos + self.L] = 1
            S_total[4 * self.up_neighbor[pos] + self.U, 4 * pos + self.U] = 1
            S_total[4 * self.down_neighbor[pos] + self.D, 4 * pos + self.D] = 1

        I_N = np.eye(self.N)
        C_total = np.kron(I_N, coin)
        return S_total @ C_total

    def get_initial_state(self, pos=0, coin_state=0):
        """Initial state: position (0,0), coin state R (0)."""
        psi = np.zeros(self.dim, dtype=complex)
        psi[4 * pos + coin_state] = 1.0
        return psi

    def check_revival(self, U, max_N=50, tol=1e-8):
        """Check for revivals up to max_N steps."""
        psi0 = self.get_initial_state()
        psi = psi0.copy()

        revivals = []
        fidelities = []

        for N in range(1, max_N + 1):
            psi = U @ psi
            fidelity = np.abs(np.vdot(psi0, psi))**2
            fidelities.append(fidelity)
            if fidelity > 1 - tol:
                revivals.append(N)

        return revivals, fidelities


def explore_phase_effects():
    """
    Explore how phases affect revival behavior on the 2×2 torus.
    """
    print("\n" + "=" * 80)
    print("EXPLORING PHASE EFFECTS ON 2×2 TORUS REVIVALS")
    print("=" * 80)

    walk = NonSeparableWalkPhased(2, 2)

    # Base symmetric Grover (p=q=r=s=0.25, no phases)
    print("\n1. Base symmetric Grover (p=q=r=s=0.25, all phases = 0):")
    coin_base = FullyParameterized4x4Coin.grover_like_bias(0.25, 0.25, 0.25, 0.25)
    U = walk.build_evolution_operator(coin_base)
    revivals, _ = walk.check_revival(U, max_N=30)
    print(f"   Revivals at N = {revivals}")

