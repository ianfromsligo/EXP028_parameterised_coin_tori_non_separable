def scan_phase_parameter(n=2, m=2):
    """
    Scan over a phase parameter to see how revivals change.
    """
    print(f"\n{'=' * 60}")
    print(f"SCANNING PHASE φ_R on {n}×{m} torus")
    print(f"{'=' * 60}")

    walk = NonSeparableWalkPhased(n, m)

    phase_values = np.linspace(0, 2*np.pi, 20)
    revival_periods = []

    for phi in phase_values:
        coin = FullyParameterized4x4Coin.grover_like_bias(0.25, 0.25, 0.25, 0.25, phi_R=phi)
        U = walk.build_evolution_operator(coin)
        revivals, _ = walk.check_revival(U, max_N=30)

        if revivals:
            revival_periods.append(revivals[0])
            print(f"   φ_R = {phi/np.pi:.2f}π: revival at N={revivals[0]}")
        else:
            revival_periods.append(0)
            print(f"   φ_R = {phi/np.pi:.2f}π: no revival")

    # Plot results
    fig, ax = plt.subplots(figsize=(10, 6))

    # Filter zero values for plotting
    nonzero_phi = [phase_values[i] for i in range(len(phase_values)) if revival_periods[i] > 0]
    nonzero_periods = [revival_periods[i] for i in range(len(phase_values)) if revival_periods[i] > 0]

    ax.plot(phase_values/np.pi, revival_periods, 'b-', linewidth=2, alpha=0.5)
    ax.plot(np.array(nonzero_phi)/np.pi, nonzero_periods, 'ro', markersize=6)
    ax.set_xlabel('φ_R / π', fontsize=12)
    ax.set_ylabel('Revival Period N', fontsize=12)
    ax.set_title(f'Effect of Right-Direction Phase on {n}×{m} Torus Revival', fontsize=14)
    ax.set_xticks([0, 0.5, 1, 1.5, 2])
    ax.set_xticklabels(['0', '0.5π', 'π', '1.5π', '2π'])
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(f'phase_scan_phiR_{n}x{m}.png', dpi=150, bbox_inches='tight')
    plt.show()
    print(f"\nSaved: phase_scan_phiR_{n}x{m}.png")


