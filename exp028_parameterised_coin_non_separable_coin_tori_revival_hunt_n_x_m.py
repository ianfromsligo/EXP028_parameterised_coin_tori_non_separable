class Parameterized4x4Coin:
    """Parameterized 4×4 SU(4) unitary coin operator."""

    @staticmethod
    def dukes_2x2(rho, alpha, beta):
        """Dukes' 2×2 SU(2) coin."""
        return np.array([
            [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * alpha)],
            [np.sqrt(1-rho) * np.exp(1j * beta), -np.sqrt(rho) * np.exp(1j * (alpha + beta))]
        ])

    @staticmethod
    def separable_4x4(rho_x, alpha_x, beta_x, rho_y, alpha_y, beta_y):
        """Separable 4×4 coin: C = C_x ⊗ C_y (6 parameters)."""
        C_x = Parameterized4x4Coin.dukes_2x2(rho_x, alpha_x, beta_x)
        C_y = Parameterized4x4Coin.dukes_2x2(rho_y, alpha_y, beta_y)
        return np.kron(C_x, C_y)

    @staticmethod
    def grover_like_bias(p, q, r, s, phi=0):
        """Grover-like biased coin (4 parameters)."""
        sqrt_p, sqrt_q, sqrt_r, sqrt_s = np.sqrt(p), np.sqrt(q), np.sqrt(r), np.sqrt(s)

        C = np.array([
            [sqrt_p, sqrt_q, sqrt_r, sqrt_s],
            [sqrt_p, -sqrt_q, sqrt_r, -sqrt_s],
            [sqrt_p, sqrt_q, -sqrt_r, -sqrt_s],
            [sqrt_p, -sqrt_q, -sqrt_r, sqrt_s]
        ])
        return C * np.exp(1j * phi)

    @staticmethod
    def random_su4():
        """Generate a random SU(4) matrix."""
        H = np.random.randn(4, 4) + 1j * np.random.randn(4, 4)
        H = H + H.conj().T
        H = H - np.trace(H) / 4 * np.eye(4)
        return expm(1j * H)


class NonSeparableWalkParameterized:
    """Non-separable quantum walk on torus with parameterized coin."""

    def __init__(self, n, m):
        self.n = n
        self.m = m
        self.N = n * m
        self.dim = 4 * self.N
        self.R, self.L, self.U, self.D = 0, 1, 2, 3
        self._build_neighbors()

    def _build_neighbors(self):
        self.right_neighbor = np.zeros(self.N, dtype=int)
        self.left_neighbor = np.zeros(self.N, dtype=int)
        self.up_neighbor = np.zeros(self.N, dtype=int)
        self.down_neighbor = np.zeros(self.N, dtype=int)

        for i in range(self.n):
            for j in range(self.m):
                idx = i * self.m + j
                self.right_neighbor[idx] = i * self.m + ((j + 1) % self.m)
                self.left_neighbor[idx] = i * self.m + ((j - 1) % self.m)
                self.up_neighbor[idx] = ((i - 1) % self.n) * self.m + j
                self.down_neighbor[idx] = ((i + 1) % self.n) * self.m + j

    def build_evolution_operator(self, coin):
        """Build U = S · (I_N ⊗ C)."""
        S_total = np.zeros((self.dim, self.dim), dtype=complex)

        for pos in range(self.N):
            S_total[4 * self.right_neighbor[pos] + self.R, 4 * pos + self.R] = 1
            S_total[4 * self.left_neighbor[pos] + self.L, 4 * pos + self.L] = 1
            S_total[4 * self.up_neighbor[pos] + self.U, 4 * pos + self.U] = 1
            S_total[4 * self.down_neighbor[pos] + self.D, 4 * pos + self.D] = 1

        I_N = np.eye(self.N)
        C_total = np.kron(I_N, coin)
        return S_total @ C_total

    def get_initial_state(self, pos=0, coin_state=0):
        """Initial state: position (0,0), coin state R (0)."""
        psi = np.zeros(self.dim, dtype=complex)
        psi[4 * pos + coin_state] = 1.0
        return psi

    def check_revival(self, U, max_N=50, tol=1e-8):
        """Check for revivals up to max_N steps."""
        psi0 = self.get_initial_state()
        psi = psi0.copy()

        revivals = []
        fidelities = []

        for N in range(1, max_N + 1):
            psi = U @ psi
            fidelity = np.abs(np.vdot(psi0, psi))**2
            fidelities.append(fidelity)
            if fidelity > 1 - tol:
                revivals.append(N)

        return revivals, fidelities


def analyze_parameter_sensitivity(n, m, param_range, param_name='p'):
    """
    Analyze how revival period changes with a parameter.

    Parameters:
    - n, m: torus dimensions
    - param_range: array of parameter values to test
    - param_name: 'p', 'q', or 'r' (bias parameters)
    """
    print(f"\n{'=' * 60}")
    print(f"Parameter sensitivity: {param_name} on {n}×{m} torus")
    print(f"{'=' * 60}")

    walk = NonSeparableWalkParameterized(n, m)

    revival_periods = []
    all_revivals = []

    for val in param_range:
        if param_name == 'p':
            # Keep q=r=s balanced
            remaining = 1 - val
            q = r = s = remaining / 3
            coin = Parameterized4x4Coin.grover_like_bias(val, q, r, s)
        elif param_name == 'q':
            remaining = 1 - val
            p = r = s = remaining / 3
            coin = Parameterized4x4Coin.grover_like_bias(p, val, r, s)
        elif param_name == 'r':
            remaining = 1 - val
            p = q = s = remaining / 3
            coin = Parameterized4x4Coin.grover_like_bias(p, q, val, s)
        else:
            continue

        U = walk.build_evolution_operator(coin)
        revivals, fidelities = walk.check_revival(U, max_N=40)

        if revivals:
            revival_periods.append(revivals[0])
            all_revivals.append(revivals)
            print(f"   {param_name}={val:.3f}: revival at N={revivals[0]}")
        else:
            revival_periods.append(0)
            all_revivals.append([])
            print(f"   {param_name}={val:.3f}: no revival")

    return revival_periods, all_revivals


def visualize_parameter_sensitivity(n, m, param_range, revival_periods, param_name='p'):
    """Plot revival period vs parameter."""
    fig, ax = plt.subplots(figsize=(10, 6))

    # Filter out zero values for plotting
    nonzero_x = [param_range[i] for i in range(len(param_range)) if revival_periods[i] > 0]
    nonzero_y = [revival_periods[i] for i in range(len(param_range)) if revival_periods[i] > 0]

    ax.plot(param_range, revival_periods, 'b-', linewidth=2, alpha=0.5, label='Revival period')
    ax.plot(nonzero_x, nonzero_y, 'bo', markersize=6, label='Revival detected')

    ax.set_xlabel(f'Parameter {param_name}', fontsize=12)
    ax.set_ylabel('Revival Period N', fontsize=12)
    ax.set_title(f'Revival Period vs {param_name} on {n}×{m} Torus', fontsize=14)
    ax.grid(True, alpha=0.3)

    # Mark the symmetric Grover point
    if param_name == 'p' and 0.25 in param_range:
        idx = np.where(np.abs(param_range - 0.25) < 0.01)[0]
        if len(idx) > 0 and revival_periods[idx[0]] > 0:
            ax.axvline(x=0.25, color='green', linestyle='--', alpha=0.7,
                      label='Symmetric Grover (p=0.25)')

    ax.legend()
    plt.tight_layout()
    plt.savefig(f'parameter_sensitivity_{n}x{m}_{param_name}.png', dpi=150, bbox_inches='tight')
    plt.show()
    print(f"Saved: parameter_sensitivity_{n}x{m}_{param_name}.png")


def search_parameterized_revivals(n, m, max_N=30):
    """
    Search for revivals using various parameterized coin strategies.
    """
    print(f"\n{'=' * 60}")
    print(f"Searching for revivals on {n}×{m} torus")
    print(f"{'=' * 60}")

    walk = NonSeparableWalkParameterized(n, m)

    results = {}

    # 1. Test Dukes' separable coin (baseline)
    print("\n1. Separable coin (Dukes' parameterization):")

    # Try known revivals from EXP025
    test_params = [
        (0.5, 0, 0, 0.5, 0, 0),   # 2×2: N=2 expected
        (0.75, 0, 0, 0.75, 0, 0), # 4×4: N=6 expected
    ]

    for params in test_params:
        rho_x, alpha_x, beta_x, rho_y, alpha_y, beta_y = params
        coin = Parameterized4x4Coin.separable_4x4(rho_x, alpha_x, beta_x,
                                                   rho_y, alpha_y, beta_y)
        U = walk.build_evolution_operator(coin)
        revivals, _ = walk.check_revival(U, max_N=max_N)
        if revivals:
            print(f"   ✓ Separable coin: revivals at N = {revivals}")
            results['separable'] = revivals

    # 2. Test Grover-like biased coin
    print("\n2. Grover-like biased coin (p, q, r, s with p+q+r+s=1):")

    # Symmetric Grover
    coin = Parameterized4x4Coin.grover_like_bias(0.25, 0.25, 0.25, 0.25)
    U = walk.build_evolution_operator(coin)
    revivals, _ = walk.check_revival(U, max_N=max_N)
    if revivals:
        print(f"   ✓ Grover (symmetric): revivals at N = {revivals}")
        results['grover'] = revivals

    # Biased cases
    biases = [
        (0.5, 0.5, 0, 0),      # Only R and L
        (0.5, 0, 0.5, 0),      # Only R and U
        (0.4, 0.3, 0.2, 0.1),  # Uneven bias
    ]

    for bias in biases:
        p, q, r, s = bias
        coin = Parameterized4x4Coin.grover_like_bias(p, q, r, s)
        U = walk.build_evolution_operator(coin)
        revivals, _ = walk.check_revival(U, max_N=max_N)
        if revivals:
            print(f"   ✓ Biased ({p},{q},{r},{s}): revivals at N = {revivals}")
            results[f'biased_{p}'] = revivals

    # 3. Systematic sweep
    print("\n3. Systematic sweep on Grover-like bias parameters:")
    print("   Testing p, q, r from 0.1 to 0.7 in steps of 0.2")

    systematic_count = 0
    for p in np.arange(0.1, 0.8, 0.2):
        for q in np.arange(0.1, 0.8, 0.2):
            for r in np.arange(0.1, 0.8, 0.2):
                s = 1 - p - q - r
                if s > 0:
                    coin = Parameterized4x4Coin.grover_like_bias(p, q, r, s)
                    U = walk.build_evolution_operator(coin)
                    revivals, _ = walk.check_revival(U, max_N=min(max_N, 30))
                    if revivals:
                        systematic_count += 1
                        if systematic_count <= 5:  # Print first few
                            print(f"   ✓ p={p:.1f}, q={q:.1f}, r={r:.1f}: revivals at N = {revivals[:5]}...")

    print(f"   Total: {systematic_count} configurations with revivals")
    results['systematic_count'] = systematic_count

    return results


